//! The timezone model: php's three `timezone_type` shapes, offset lookup
//! through the IANA database, and the local-time → timestamp resolution rule
//! php uses across a DST transition.

use jiff::tz::{AmbiguousOffset, TimeZone};
use jiff::Timestamp;

/// A php timezone, in the three shapes `timezone_type` names.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) enum Tz {
    /// `timezone_type` 1 — a fixed offset in seconds east of UTC.
    Offset(i32),
    /// `timezone_type` 2 — an abbreviation with its fixed offset and DST flag.
    Abbr {
        name: String,
        offset: i32,
        dst: bool,
    },
    /// `timezone_type` 3 — an IANA identifier, kept with the spelling the
    /// caller used: php echoes `new DateTimeZone("europe/BERLIN")->getName()`
    /// back verbatim.
    Id(String),
}

impl Tz {
    /// php's `timezone_type`.
    pub(crate) fn type_id(&self) -> i64 {
        match self {
            Tz::Offset(_) => 1,
            Tz::Abbr { .. } => 2,
            Tz::Id(_) => 3,
        }
    }

    /// php's `DateTimeZone::getName()` and the `e` format character.
    pub(crate) fn name(&self) -> String {
        match self {
            Tz::Offset(secs) => render_offset(*secs),
            Tz::Abbr { name, .. } => name.clone(),
            Tz::Id(id) => id.clone(),
        }
    }

    /// UTC.
    pub(crate) fn utc() -> Tz {
        Tz::Id("UTC".to_string())
    }

    /// The offset, abbreviation (`T`) and DST flag (`I`) in force at `ts`.
    pub(crate) fn info(&self, ts: i64) -> (i32, String, bool) {
        match self {
            Tz::Offset(secs) => (*secs, gmt_abbr(*secs), false),
            Tz::Abbr { name, offset, dst } => (*offset, name.clone(), *dst),
            Tz::Id(id) => match TimeZone::get(id) {
                Ok(tz) => {
                    let info = tz.to_offset_info(clamp_ts(ts));
                    (
                        info.offset().seconds(),
                        info.abbreviation().to_string(),
                        info.dst().is_dst(),
                    )
                }
                // Unreachable for a `Tz::Id` that came through `parse`, which
                // only builds one after the database accepted the name.
                Err(_) => (0, "UTC".to_string(), false),
            },
        }
    }

    /// The offset in force at `ts`.
    pub(crate) fn offset_at(&self, ts: i64) -> i32 {
        self.info(ts).0
    }

    /// The timestamp of a local wall-clock time, given as `sse` — the civil
    /// datetime read as if it were UTC (php's "seconds since epoch" of an
    /// unresolved `timelib_time`).
    ///
    /// Across a DST transition php is not simply "earlier" or "later":
    ///
    /// * a **gap** (spring forward) takes the offset from *before* the
    ///   transition, so `2021-03-28 02:30` in `Europe/Berlin` becomes
    ///   `03:30+02:00`;
    /// * an **overlap** (fall back) takes `prefer` when it is one of the two
    ///   candidates — that is the offset the `DateTime` already carried, which
    ///   is why `$d->modify(…)` and `mktime()` can land on a different
    ///   instant than `strtotime()` for the same wall clock — and otherwise
    ///   the offset in force at `sse` itself, which is what a fresh parse
    ///   does.
    pub(crate) fn resolve(&self, sse: i64, prefer: Option<i32>) -> i64 {
        match self {
            Tz::Offset(secs) => sse - *secs as i64,
            Tz::Abbr { offset, .. } => sse - *offset as i64,
            Tz::Id(id) => {
                let Ok(tz) = TimeZone::get(id) else {
                    return sse;
                };
                let (y, mo, d) = super::civil::civil_from_days(sse.div_euclid(86_400));
                let rem = sse.rem_euclid(86_400);
                let dt = i16::try_from(y).ok().and_then(|y| {
                    jiff::civil::DateTime::new(
                        y,
                        mo as i8,
                        d as i8,
                        (rem / 3600) as i8,
                        ((rem / 60) % 60) as i8,
                        (rem % 60) as i8,
                        0,
                    )
                    .ok()
                });
                // Outside the database's year range there are no transitions
                // to reason about; take the offset the zone reports there.
                let Some(dt) = dt else {
                    return sse - self.offset_at(sse) as i64;
                };
                let offset = match tz.to_ambiguous_timestamp(dt).offset() {
                    AmbiguousOffset::Unambiguous { offset } => offset.seconds(),
                    AmbiguousOffset::Gap { before, .. } => before.seconds(),
                    AmbiguousOffset::Fold { before, after } => {
                        let (b, a) = (before.seconds(), after.seconds());
                        match prefer {
                            Some(p) if p == b || p == a => p,
                            _ => {
                                let at_sse = self.offset_at(sse);
                                if at_sse == b || at_sse == a {
                                    at_sse
                                } else {
                                    a
                                }
                            }
                        }
                    }
                };
                sse - offset as i64
            }
        }
    }

    /// php's `DateTimeZone::__construct()`: an offset, then an abbreviation,
    /// then an IANA identifier. `UTC` is the one abbreviation php resolves as
    /// an identifier instead (`timezone_type` 3).
    pub(crate) fn parse(s: &str) -> Option<Tz> {
        if let Some(secs) = parse_offset(s) {
            return Some(Tz::Offset(secs));
        }
        if s.eq_ignore_ascii_case("utc") {
            return Some(Tz::Id(s.to_string()));
        }
        if let Some((offset, dst)) = lookup_abbr(s) {
            return Some(Tz::Abbr {
                name: s.to_string(),
                offset,
                dst,
            });
        }
        if is_known_id(s) {
            return Some(Tz::Id(s.to_string()));
        }
        None
    }
}

/// Whether php's database knows `name` (case-insensitively, as php matches
/// it): `date_default_timezone_set` accepts exactly these, abbreviations
/// included only when tzdata ships a zone of that name — `CET` yes, `Z` no.
/// The platform database is not asked, because it carries names php's
/// snapshot does not.
pub(crate) fn is_known_id(name: &str) -> bool {
    !name.is_empty()
        && IDENTIFIERS
            .iter()
            .any(|(id, _, _)| id.eq_ignore_ascii_case(name))
}

/// A timestamp the zone database can be asked about.
///
/// php extrapolates a zone's last rule forwards for ever, so `date("T",
/// 1e17)` in `Europe/Berlin` is still `CEST` in September. jiff's calendar
/// stops at year 9999, so a timestamp past that is moved back whole
/// 400-year Gregorian cycles: 146 097 days is exactly 20 871 weeks, so the
/// weekday and the day of the month — everything a DST rule keys on — are
/// unchanged. Before the first transition a zone has one constant offset, so
/// a timestamp below the range is simply clamped.
fn clamp_ts(ts: i64) -> Timestamp {
    /// 0001-01-01T00:00:00Z.
    const LOW: i64 = -62_135_596_800;
    /// 9000-01-01T00:00:00Z, comfortably inside jiff's range.
    const HIGH: i64 = 221_845_046_400;
    /// 400 Gregorian years.
    const CYCLE: i64 = 12_622_780_800;
    let ts = if ts > HIGH {
        ts - ((ts - HIGH + CYCLE - 1) / CYCLE) * CYCLE
    } else {
        ts.max(LOW)
    };
    Timestamp::from_second(ts).unwrap_or(if ts < 0 {
        Timestamp::MIN
    } else {
        Timestamp::MAX
    })
}

/// `+05:30`, `-08:00`, `+01:00:30` — php prints the seconds only when they
/// are not zero.
pub(crate) fn render_offset(secs: i32) -> String {
    let sign = if secs < 0 { '-' } else { '+' };
    let a = secs.unsigned_abs();
    let (h, m, s) = (a / 3600, (a / 60) % 60, a % 60);
    if s == 0 {
        format!("{sign}{h:02}:{m:02}")
    } else {
        format!("{sign}{h:02}:{m:02}:{s:02}")
    }
}

/// The `T` of a fixed-offset zone: `GMT+0530`.
fn gmt_abbr(secs: i32) -> String {
    let sign = if secs < 0 { '-' } else { '+' };
    let a = secs.unsigned_abs();
    format!("GMT{sign}{:02}{:02}", a / 3600, (a / 60) % 60)
}

/// `+5`, `+05`, `+0530`, `+05:30`, `+01:00:30` and the `GMT`-prefixed forms
/// (php accepts the prefix only in upper case).
pub(crate) fn parse_offset(s: &str) -> Option<i32> {
    let body = s.strip_prefix("GMT").unwrap_or(s);
    let (sign, rest) = match body.as_bytes().first()? {
        b'+' => (1i32, &body[1..]),
        b'-' => (-1i32, &body[1..]),
        _ => return None,
    };
    let digits: Vec<u8> = rest.bytes().filter(|b| *b != b':').collect();
    if digits.is_empty() || digits.len() > 6 || !digits.iter().all(|b| b.is_ascii_digit()) {
        return None;
    }
    // `:`-separated fields are h[:m[:s]]; a bare run is HH, HHMM or HHMMSS.
    let (h, m, sec) = if rest.contains(':') {
        let mut it = rest.split(':');
        let h: i32 = it.next()?.parse().ok()?;
        let m: i32 = it.next().map_or(Some(0), |v| v.parse().ok())?;
        let sec: i32 = it.next().map_or(Some(0), |v| v.parse().ok())?;
        if it.next().is_some() {
            return None;
        }
        (h, m, sec)
    } else {
        let n = |a: usize, b: usize| -> i32 {
            digits[a..b]
                .iter()
                .fold(0, |acc, d| acc * 10 + (d - b'0') as i32)
        };
        match digits.len() {
            1 | 2 => (n(0, digits.len()), 0, 0),
            3 => (n(0, 1), n(1, 3), 0),
            4 => (n(0, 2), n(2, 4), 0),
            5 => (n(0, 1), n(1, 3), n(3, 5)),
            6 => (n(0, 2), n(2, 4), n(4, 6)),
            _ => return None,
        }
    };
    if m > 59 || sec > 59 {
        return None;
    }
    Some(sign * (h * 3600 + m * 60 + sec))
}

/// A timezone abbreviation's offset and DST flag, case-insensitively.
pub(crate) fn lookup_abbr(name: &str) -> Option<(i32, bool)> {
    let lower = name.to_ascii_lowercase();
    ABBREVIATIONS
        .iter()
        .find(|(n, _, _)| *n == lower)
        .map(|(_, off, dst)| (*off, *dst))
}

