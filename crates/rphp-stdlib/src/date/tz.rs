#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_the_three_timezone_shapes() {
        assert_eq!(Tz::parse("+05:30"), Some(Tz::Offset(19_800)));
        assert_eq!(Tz::parse("GMT+5"), Some(Tz::Offset(18_000)));
        assert_eq!(Tz::parse("-08"), Some(Tz::Offset(-28_800)));
        assert_eq!(Tz::parse("+01:00:30"), Some(Tz::Offset(3_630)));
        assert_eq!(Tz::parse("0530"), None);
        assert_eq!(Tz::parse("gmt+5"), None);
        assert_eq!(Tz::parse("UTC").map(|t| t.type_id()), Some(3));
        assert_eq!(Tz::parse("GMT").map(|t| t.type_id()), Some(2));
        assert_eq!(Tz::parse("CET").map(|t| t.type_id()), Some(2));
        assert_eq!(Tz::parse("PST8PDT").map(|t| t.type_id()), Some(3));
        assert_eq!(Tz::parse("Europe/Berlin").map(|t| t.type_id()), Some(3));
        assert_eq!(Tz::parse("Nowhere/Nothing"), None);
        assert_eq!(Tz::parse("+05:30").unwrap().name(), "+05:30");
        assert_eq!(Tz::parse("+01:00:30").unwrap().name(), "+01:00:30");
    }

    #[test]
    fn resolves_local_time_across_a_dst_transition() {
        let berlin = Tz::Id("Europe/Berlin".to_string());
        // The gap: 02:30 does not exist and php reports 03:30+02:00.
        let sse = 1_616_898_600; // 2021-03-28 02:30 read as UTC
        assert_eq!(berlin.resolve(sse, None), 1_616_895_000);
        // The overlap: a fresh parse takes CET, a `modify` from a CEST
        // instant keeps CEST.
        let sse = 1_635_647_400; // 2021-10-31 02:30 read as UTC
        assert_eq!(berlin.resolve(sse, None), 1_635_643_800);
        assert_eq!(berlin.resolve(sse, Some(7_200)), 1_635_640_200);
        assert_eq!(berlin.resolve(sse, Some(3_600)), 1_635_643_800);
        // New York folds the other way round: the offset at `sse` is the
        // *earlier* of the two.
        let ny = Tz::Id("America/New_York".to_string());
        assert_eq!(ny.resolve(1_636_248_600, None), 1_636_263_000);
        assert_eq!(ny.resolve(1_615_689_000, None), 1_615_707_000);
    }

    #[test]
    fn reports_offsets_abbreviations_and_dst() {
        let berlin = Tz::Id("Europe/Berlin".to_string());
        assert_eq!(
            berlin.info(1_626_343_200),
            (7_200, "CEST".to_string(), true)
        );
        assert_eq!(
            berlin.info(1_610_708_400),
            (3_600, "CET".to_string(), false)
        );
        assert_eq!(Tz::Offset(19_800).info(0).1, "GMT+0530");
        assert_eq!(Tz::Offset(-28_800).info(0).1, "GMT-0800");
    }
}
