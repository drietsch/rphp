        let e = escape_html("a & b < c > d \" e ' f".as_bytes(), false, 3, Charset::Utf8, true);
        assert_eq!(e, b"a &amp; b &lt; c &gt; d &quot; e &#039; f");
        assert_eq!(unescape_html(&e, true, 3, Charset::Utf8), "a & b < c > d \" e ' f".as_bytes());
