//! HTML entity functions (php-src `ext/standard/html.c`): `htmlspecialchars`,
//! `htmlspecialchars_decode`, `htmlentities`, `html_entity_decode`,
//! `get_html_translation_table`, with the full `ENT_*` flag set (quote style,
//! document type, `ENT_SUBSTITUTE`/`ENT_IGNORE` for malformed input,
//! `ENT_DISALLOWED`, `$double_encode`). The named-entity tables at the bottom
//! are generated from the oracle (`get_html_translation_table`) and the WHATWG
//! entity list; the single-byte charset tables from iconv. UTF-8 is exact;
//! the single-byte charsets php supports are exact; the multibyte legacy
//! charsets (BIG5, GB2312, Shift_JIS, EUC-JP) get basic substitution only and
//! no malformed-sequence detection.
use std::sync::OnceLock;

use rphp_value::{Array, ArrayKey, Value};

use rphp_runtime::{nf, Ctx, NativeFn, NativeResult, Unwind};

use crate::strings::str_value;

/// Functions this module provides.
pub(crate) static FUNCTIONS: &[NativeFn] = &[
    nf!("htmlspecialchars", 1, Some(4), htmlspecialchars),
    nf!("htmlspecialchars_decode", 1, Some(2), htmlspecialchars_decode),
    nf!("htmlentities", 1, Some(4), htmlentities),
    nf!("html_entity_decode", 1, Some(3), html_entity_decode),
    nf!("get_html_translation_table", 0, Some(3), get_html_translation_table),
];

const ENT_HTML_QUOTE_SINGLE: i64 = 1;
const ENT_HTML_QUOTE_DOUBLE: i64 = 2;
const ENT_IGNORE: i64 = 4;
const ENT_SUBSTITUTE: i64 = 8;
const ENT_DISALLOWED: i64 = 128;
const ENT_DOC_MASK: i64 = 48;
/// `ENT_QUOTES | ENT_SUBSTITUTE | ENT_HTML401`, the 8.1+ default.
const DEFAULT_FLAGS: i64 = 11;

/// The document type selected by `ENT_HTML401`/`ENT_XML1`/`ENT_XHTML`/`ENT_HTML5`.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Doc {
    Html401,
    Xml1,
    Xhtml,
    Html5,
}

impl Doc {
    fn from_flags(flags: i64) -> Doc {
        match flags & ENT_DOC_MASK {
            16 => Doc::Xml1,
            32 => Doc::Xhtml,
            48 => Doc::Html5,
            _ => Doc::Html401,
        }
    }
}

/// A supported charset.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Charset {
    Utf8,
    Latin1,
    Latin9,
    Cp1252,
    Koi8r,
    Cp1251,
    Iso8859_5,
    Cp866,
    MacRoman,
    /// The legacy multibyte charsets: basic substitution only, but their
    /// sequence structure is validated like php does.
    Big5,
    Gb2312,
    Big5Hkscs,
    Sjis,
    EucJp,
}

impl Charset {
    /// php's `determine_charset`: the hint (case-insensitive alias list), or
    /// UTF-8 with a warning for an unknown name; empty/null means UTF-8.
    fn from_hint(ctx: &mut Ctx, func: &str, hint: Option<&[u8]>) -> Result<Charset, Unwind> {
        // No (or an empty) hint means the `default_charset` ini directive.
        let from_ini: Vec<u8>;
        let hint: &[u8] = match hint.filter(|h| !h.is_empty()) {
            Some(h) => h,
            None => {
                from_ini = ctx.ini_get("default_charset").unwrap_or("UTF-8").as_bytes().to_vec();
                if from_ini.is_empty() {
                    return Ok(Charset::Utf8);
                }
                &from_ini
            }
        };
        let h = hint.to_ascii_lowercase();
        let cs = match h.as_slice() {
            b"iso-8859-1" | b"iso8859-1" => Charset::Latin1,
            b"iso-8859-15" | b"iso8859-15" => Charset::Latin9,
            b"utf-8" => Charset::Utf8,
            b"cp1252" | b"windows-1252" | b"1252" => Charset::Cp1252,
            b"big5" | b"950" => Charset::Big5,
            b"gb2312" | b"936" => Charset::Gb2312,
            b"big5-hkscs" => Charset::Big5Hkscs,
            b"shift_jis" | b"sjis" | b"932" | b"sjis-win" | b"cp932" => Charset::Sjis,
            b"eucjp" | b"euc-jp" | b"eucjp-win" => Charset::EucJp,
            b"koi8-r" | b"koi8-ru" | b"koi8r" => Charset::Koi8r,
            b"cp1251" | b"windows-1251" | b"win-1251" => Charset::Cp1251,
            b"iso8859-5" | b"iso-8859-5" => Charset::Iso8859_5,
            b"cp866" | b"866" | b"ibm866" => Charset::Cp866,
            b"macroman" => Charset::MacRoman,
            _ => {
                ctx.warn(&format!(
                    "{func}(): Charset \"{}\" is not supported, assuming UTF-8",
                    String::from_utf8_lossy(hint)
                ))?;
                Charset::Utf8
            }
        };
        Ok(cs)
    }

    /// Whether this is one of the legacy multibyte charsets.
    fn is_multibyte(self) -> bool {
        matches!(self, Charset::Big5 | Charset::Gb2312 | Charset::Big5Hkscs | Charset::Sjis | Charset::EucJp)
    }

    /// The byte → code point table of a single-byte charset (bytes ≥ 0x80).
    fn high_table(self) -> Option<&'static [u32; 128]> {
        match self {
            Charset::Latin9 => Some(&ISO_8859_15),
            Charset::Cp1252 => Some(&CP1252),
            Charset::Koi8r => Some(&KOI8_R),
            Charset::Cp1251 => Some(&CP1251),
            Charset::Iso8859_5 => Some(&ISO_8859_5),
            Charset::Cp866 => Some(&CP866),
            Charset::MacRoman => Some(&MACROMAN),
            _ => None,
        }
    }

    /// A single-byte charset's byte as a Unicode code point (`None` when the
    /// byte is undefined in that charset — php's MacRoman table also leaves
    /// tab and newline unmapped, so they never become `&Tab;`/`&NewLine;`).
    fn to_unicode(self, b: u8) -> Option<u32> {
        if b < 0x80 {
            if self == Charset::MacRoman && (b == 0x09 || b == 0x0a) {
                return None;
            }
            return Some(b as u32);
        }
        match self {
            Charset::Latin1 => Some(b as u32),
            cs => match cs.high_table() {
                Some(t) => Some(t[(b - 0x80) as usize]).filter(|&cp| cp != 0),
                None => None,
            },
        }
    }

    /// Encode a code point in this charset (`None` when not representable).
    fn encode_cp(self, cp: u32) -> Option<Vec<u8>> {
        match self {
            Charset::Utf8 => Some(utf8_encode(cp)),
            Charset::Latin1 => (cp <= 0xff).then(|| vec![cp as u8]),
            cs if cs.is_multibyte() => (cp < 0x80).then(|| vec![cp as u8]),
            cs => {
                if cp < 0x80 {
                    return Some(vec![cp as u8]);
                }
                let t = cs.high_table()?;
                t.iter().position(|&u| u == cp && u != 0).map(|i| vec![0x80 + i as u8])
            }
        }
    }
}

/// UTF-8 encode a code point (surrogates and out-of-range values are the
/// caller's problem; they never reach here).
fn utf8_encode(cp: u32) -> Vec<u8> {
    let mut out = Vec::with_capacity(4);
    if cp < 0x80 {
        out.push(cp as u8);
    } else if cp < 0x800 {
        out.push(0xc0 | (cp >> 6) as u8);
        out.push(0x80 | (cp & 0x3f) as u8);
    } else if cp < 0x10000 {
        out.push(0xe0 | (cp >> 12) as u8);
        out.push(0x80 | ((cp >> 6) & 0x3f) as u8);
        out.push(0x80 | (cp & 0x3f) as u8);
    } else {
        out.push(0xf0 | (cp >> 18) as u8);
        out.push(0x80 | ((cp >> 12) & 0x3f) as u8);
        out.push(0x80 | ((cp >> 6) & 0x3f) as u8);
        out.push(0x80 | (cp & 0x3f) as u8);
    }
    out
}

fn utf8_trail(c: u8) -> bool {
    (0x80..=0xbf).contains(&c)
}

fn utf8_lead(c: u8) -> bool {
    c < 0x80 || (0xc2..=0xf4).contains(&c)
}

/// php's `php_next_utf8_char`: decode one UTF-8 sequence at `*pos`, advancing
/// past it. On a malformed sequence returns `None` and advances by the number
/// of bytes php charges to the error (one replacement character each).
pub(crate) fn next_utf8_char(s: &[u8], pos: &mut usize) -> Option<u32> {
    let p = *pos;
    let avail = s.len() - p;
    let c = s[p];
    let fail = |pos: &mut usize, n: usize| {
        *pos += n;
        None
    };
    if c < 0x80 {
        *pos += 1;
        Some(c as u32)
    } else if c < 0xc2 {
        fail(pos, 1)
    } else if c < 0xe0 {
        if avail < 2 {
            return fail(pos, 1);
        }
        if !utf8_trail(s[p + 1]) {
            return fail(pos, if utf8_lead(s[p + 1]) { 1 } else { 2 });
        }
        let cp = ((c as u32 & 0x1f) << 6) | (s[p + 1] as u32 & 0x3f);
        if cp < 0x80 {
            return fail(pos, 2);
        }
        *pos += 2;
        Some(cp)
    } else if c < 0xf0 {
        if avail < 3 || !utf8_trail(s[p + 1]) || !utf8_trail(s[p + 2]) {
            if avail < 2 || utf8_lead(s[p + 1]) {
                return fail(pos, 1);
            }
            if avail < 3 || utf8_lead(s[p + 2]) {
                return fail(pos, 2);
            }
            return fail(pos, 3);
        }
        let cp = ((c as u32 & 0x0f) << 12) | ((s[p + 1] as u32 & 0x3f) << 6) | (s[p + 2] as u32 & 0x3f);
        if cp < 0x800 || (0xd800..=0xdfff).contains(&cp) {
            return fail(pos, 3);
        }
        *pos += 3;
        Some(cp)
    } else if c < 0xf5 {
        if avail < 4 || !utf8_trail(s[p + 1]) || !utf8_trail(s[p + 2]) || !utf8_trail(s[p + 3]) {
            if avail < 2 || utf8_lead(s[p + 1]) {
                return fail(pos, 1);
            }
            if avail < 3 || utf8_lead(s[p + 2]) {
                return fail(pos, 2);
            }
            if avail < 4 || utf8_lead(s[p + 3]) {
                return fail(pos, 3);
            }
            return fail(pos, 4);
        }
        let cp = ((c as u32 & 0x07) << 18)
            | ((s[p + 1] as u32 & 0x3f) << 12)
            | ((s[p + 2] as u32 & 0x3f) << 6)
            | (s[p + 3] as u32 & 0x3f);
        if !(0x10000..=0x10ffff).contains(&cp) {
            return fail(pos, 4);
        }
        *pos += 4;
        Some(cp)
    } else {
        fail(pos, 1)
    }
}

/// Decode one character of `cs` at `*pos`: the code point for UTF-8, the byte
/// for a single-byte charset, and the packed bytes of a legacy multibyte
/// sequence (never mistaken for a code point above ASCII). `None` marks a
/// malformed sequence; the multibyte rules follow php's `get_next_char`.
fn next_char(cs: Charset, s: &[u8], pos: &mut usize) -> Option<u32> {
    let p = *pos;
    let c = s[p];
    let avail = s.len() - p;
    // Bytes that may start a character in `cs`: a malformed sequence stops
    // in front of one of them (it gets its own turn), and swallows any other.
    let lead_like = |b: u8| -> bool {
        match cs {
            Charset::Sjis => b < 0x80 || (0x81..=0x9f).contains(&b) || (0xa1..=0xdf).contains(&b) || (0xe0..=0xfc).contains(&b),
            Charset::EucJp => b < 0xa0 || (0xa1..=0xfe).contains(&b),
            Charset::Gb2312 => b < 0x80 || (0xa1..=0xfe).contains(&b),
            _ => true,
        }
    };
    let fail = |pos: &mut usize| {
        *pos += 1;
        None
    };
    let pair = |pos: &mut usize, trail_ok: bool| {
        let t = s.get(p + 1).copied().unwrap_or(0);
        if avail < 2 || !trail_ok {
            *pos += if avail < 2 || lead_like(t) { 1 } else { 2 };
            return None;
        }
        *pos += 2;
        Some(((c as u32) << 8) | t as u32)
    };
    match cs {
        Charset::Utf8 => next_utf8_char(s, pos),
        Charset::Big5 | Charset::Big5Hkscs => {
            if c <= 0x80 || c == 0xff {
                *pos += 1;
                Some(c as u32)
            } else {
                let t = s.get(p + 1).copied().unwrap_or(0);
                pair(pos, (0x40..=0x7e).contains(&t) || (0xa1..=0xfe).contains(&t))
            }
        }
        Charset::Gb2312 => {
            if c < 0x80 {
                *pos += 1;
                Some(c as u32)
            } else if (0xa1..=0xfe).contains(&c) {
                let t = s.get(p + 1).copied().unwrap_or(0);
                pair(pos, (0xa1..=0xfe).contains(&t))
            } else {
                fail(pos)
            }
        }
        Charset::Sjis => {
            if c < 0x80 || (0xa1..=0xdf).contains(&c) {
                *pos += 1;
                Some(c as u32)
            } else if (0x81..=0x9f).contains(&c) || (0xe0..=0xfc).contains(&c) {
                let t = s.get(p + 1).copied().unwrap_or(0);
                pair(pos, (0x40..=0x7e).contains(&t) || (0x80..=0xfc).contains(&t))
            } else {
                fail(pos)
            }
        }
        Charset::EucJp => {
            if c < 0x80 || (0x80..=0x8d).contains(&c) || (0x90..=0x9f).contains(&c) {
                *pos += 1;
                Some(c as u32)
            } else if (0xa1..=0xfe).contains(&c) {
                let t = s.get(p + 1).copied().unwrap_or(0);
                pair(pos, (0xa1..=0xfe).contains(&t))
            } else if c == 0x8e {
                let t = s.get(p + 1).copied().unwrap_or(0);
                pair(pos, (0xa1..=0xdf).contains(&t))
            } else if c == 0x8f {
                let t1 = s.get(p + 1).copied().unwrap_or(0);
                let t2 = s.get(p + 2).copied().unwrap_or(0);
                let ok1 = (0xa1..=0xfe).contains(&t1);
                let ok2 = (0xa1..=0xfe).contains(&t2);
                if avail < 3 || !ok1 || !ok2 {
                    *pos += if avail < 2 || lead_like(t1) {
                        1
                    } else if avail < 3 || lead_like(t2) {
                        2
                    } else {
                        3
                    };
                    return None;
                }
                *pos += 3;
                Some(((c as u32) << 16) | ((t1 as u32) << 8) | t2 as u32)
            } else {
                fail(pos)
            }
        }
        _ => {
            *pos += 1;
            Some(c as u32)
        }
    }
}

/// `unicode_cp_is_allowed`: whether a code point may appear literally in a
/// document of this type.
fn cp_is_allowed(cp: u32, doc: Doc) -> bool {
    match doc {
        Doc::Html401 => {
            (0x20..=0x7e).contains(&cp)
                || matches!(cp, 0x09 | 0x0a | 0x0d)
                || (0xa0..=0xd7ff).contains(&cp)
                || (0xe000..=0x10ffff).contains(&cp)
        }
        Doc::Html5 => {
            (0x20..=0x7e).contains(&cp)
                || ((0x09..=0x0d).contains(&cp) && cp != 0x0b)
                || (0xa0..=0xd7ff).contains(&cp)
                || ((0xe000..=0x10ffff).contains(&cp)
                    && (cp & 0xffff) < 0xfffe
                    && !(0xfdd0..=0xfdef).contains(&cp))
        }
        Doc::Xml1 | Doc::Xhtml => {
            (0x20..=0xd7ff).contains(&cp)
                || matches!(cp, 0x09 | 0x0a | 0x0d)
                || ((0xe000..=0x10ffff).contains(&cp) && cp != 0xfffe && cp != 0xffff)
        }
    }
}

/// `numeric_entity_is_allowed`: whether `&#N;` may reference this code point.
fn numeric_entity_is_allowed(cp: u32, doc: Doc) -> bool {
    match doc {
        Doc::Html401 => cp <= 0x10ffff,
        // HTML5 forbids U+0000, U+000D, the noncharacters and the control
        // characters that are not space characters — surrogates are fine.
        Doc::Html5 => {
            cp <= 0x10ffff
                && cp != 0
                && cp != 0x0d
                && !(0xfdd0..=0xfdef).contains(&cp)
                && (cp & 0xfffe) != 0xfffe
                && !((0x01..=0x1f).contains(&cp) && !matches!(cp, 0x09 | 0x0a | 0x0c))
                && !(0x7f..=0x9f).contains(&cp)
        }
        Doc::Xml1 | Doc::Xhtml => cp_is_allowed(cp, doc),
    }
}

/// Parse `&#...;` at `s[i..]` where `s[i]` is the byte after `#`: the code
/// point and the index of the `;`.
fn parse_numeric_entity(s: &[u8], mut i: usize) -> Option<(u32, usize)> {
    let hex = matches!(s.get(i), Some(b'x') | Some(b'X'));
    if hex {
        i += 1;
    }
    let radix = if hex { 16 } else { 10 };
    let start = i;
    let mut v: u64 = 0;
    while let Some(d) = s.get(i).and_then(|&c| (c as char).to_digit(radix)) {
        v = v.saturating_mul(radix as u64).saturating_add(d as u64);
        i += 1;
    }
    if i == start || s.get(i) != Some(&b';') || v > 0x10ffff {
        return None;
    }
    Some((v as u32, i))
}

/// Parse `&name;` at `s[i..]` where `s[i]` is the byte after `&`: the name
/// bytes and the index of the `;`.
fn parse_named_entity(s: &[u8], i: usize) -> Option<(&[u8], usize)> {
    let mut j = i;
    while j < s.len() && s[j].is_ascii_alphanumeric() {
        j += 1;
    }
    if j == i || s.get(j) != Some(&b';') {
        return None;
    }
    Some((&s[i..j], j))
}

/// The HTML 4.01 name → code point map (built once).
fn html401_decode_map() -> &'static Vec<(&'static str, u32)> {
    static MAP: OnceLock<Vec<(&'static str, u32)>> = OnceLock::new();
    MAP.get_or_init(|| {
        let mut v: Vec<(&'static str, u32)> = HTML401_ENTITIES.iter().map(|&(cp, n)| (n, cp)).collect();
        v.extend([("amp", 0x26), ("lt", 0x3c), ("gt", 0x3e), ("quot", 0x22)]);
        v.sort_by(|a, b| a.0.as_bytes().cmp(b.0.as_bytes()));
        v
    })
}

/// Resolve a named entity for the document type: one or two code points.
/// `all` false restricts the lookup to the five special characters.
fn resolve_named(name: &[u8], doc: Doc, all: bool) -> Option<(u32, u32)> {
    let apos_ok = doc != Doc::Html401;
    match name {
        b"amp" => return Some((0x26, 0)),
        b"lt" => return Some((0x3c, 0)),
        b"gt" => return Some((0x3e, 0)),
        b"quot" => return Some((0x22, 0)),
        b"apos" if apos_ok => return Some((0x27, 0)),
        _ => {}
    }
    if !all {
        return None;
    }
    match doc {
        Doc::Xml1 => None,
        Doc::Html401 | Doc::Xhtml => {
            let map = html401_decode_map();
            map.binary_search_by(|(n, _)| n.as_bytes().cmp(name)).ok().map(|i| (map[i].1, 0))
        }
        Doc::Html5 => {
            let i = HTML5_DECODE.binary_search_by(|(n, _)| n.as_bytes().cmp(name)).ok()?;
            let text = HTML5_DECODE[i].1.as_bytes();
            let mut pos = 0;
            let a = next_utf8_char(text, &mut pos).unwrap_or(0);
            let b = if pos < text.len() { next_utf8_char(text, &mut pos).unwrap_or(0) } else { 0 };
            Some((a, b))
        }
    }
}

/// The named entity for a code point in the document type's table (the
/// second code point of a two-code-point HTML5 entity is looked up with
/// [`entity_for_pair`]).
fn entity_for_cp(cp: u32, doc: Doc) -> Option<&'static str> {
    let table: &[(u32, &str)] = match doc {
        Doc::Html401 | Doc::Xhtml => HTML401_ENTITIES,
        Doc::Html5 => HTML5_ENTITIES,
        Doc::Xml1 => return None,
    };
    table.binary_search_by(|(c, _)| c.cmp(&cp)).ok().map(|i| table[i].1)
}

/// The HTML5 entity for a two-code-point sequence.
fn entity_for_pair(a: u32, b: u32) -> Option<&'static str> {
    HTML5_ENTITIES_2
        .binary_search_by(|(x, y, _)| (x, y).cmp(&(&a, &b)))
        .ok()
        .map(|i| HTML5_ENTITIES_2[i].2)
}

/// The entity of one of the five special characters under the quote flags:
/// `'` is `&#039;` in HTML 4.01 and `&apos;` elsewhere.
fn special_entity(cp: u32, flags: i64, doc: Doc) -> Option<&'static str> {
    match cp {
        0x26 => Some("&amp;"),
        0x3c => Some("&lt;"),
        0x3e => Some("&gt;"),
        0x22 if flags & ENT_HTML_QUOTE_DOUBLE != 0 => Some("&quot;"),
        0x27 if flags & ENT_HTML_QUOTE_SINGLE != 0 => {
            Some(if doc == Doc::Html401 { "&#039;" } else { "&apos;" })
        }
        _ => None,
    }
}

/// php's `php_escape_html_entities_ex`: the encoder behind `htmlspecialchars`
/// (`all` false) and `htmlentities` (`all` true).
fn escape_html(
    old: &[u8],
    all: bool,
    flags: i64,
    cs: Charset,
    double_encode: bool,
) -> Vec<u8> {
    let doc = Doc::from_flags(flags);
    let replacement: &[u8] = if cs == Charset::Utf8 { b"\xEF\xBF\xBD" } else { b"&#xFFFD;" };
    let mut out = Vec::with_capacity(old.len() + old.len() / 4);
    let mut cursor = 0usize;
    while cursor < old.len() {
        let before = cursor;
        let Some(this) = next_char(cs, old, &mut cursor) else {
            if flags & ENT_IGNORE != 0 {
                continue;
            }
            if flags & ENT_SUBSTITUTE != 0 {
                out.extend_from_slice(replacement);
                continue;
            }
            return Vec::new();
        };
        let seq = &old[before..cursor];
        if this != 0x26 {
            if (this == 0x27 && flags & ENT_HTML_QUOTE_SINGLE == 0)
                || (this == 0x22 && flags & ENT_HTML_QUOTE_DOUBLE == 0)
            {
                out.extend_from_slice(seq);
                continue;
            }
            // The Unicode code point of this character, when known:
            // `htmlspecialchars` and the legacy charsets only know the ASCII
            // range below DEL (php consults the charset table only when it
            // encodes all entities).
            let uni: Option<u32> = match cs {
                Charset::Utf8 => Some(this),
                single if all && !single.is_multibyte() => single.to_unicode(this as u8),
                _ => (this < 0x7f).then_some(this),
            };
            let mut rep: Option<&str> = special_entity(this, flags, doc);
            // htmlentities() takes XHTML's apostrophe from the HTML 4.01 table.
            if all && doc == Doc::Xhtml && this == 0x27 && rep.is_some() {
                rep = Some("&#039;");
            }
            if rep.is_none() && all {
                if let Some(u) = uni {
                    if doc == Doc::Html5 {
                        // A two-code-point entity claims the next character too.
                        let mut peek = cursor;
                        if peek < old.len() {
                            if let Some(next) = next_char(cs, old, &mut peek) {
                                if let Some(e) = entity_for_pair(u, next) {
                                    rep = Some(e);
                                    cursor = peek;
                                }
                            }
                        }
                    }
                    if rep.is_none() {
                        rep = entity_for_cp(u, doc);
                    }
                }
            }
            match rep {
                Some(e) => {
                    if e.starts_with('&') {
                        out.extend_from_slice(e.as_bytes());
                    } else {
                        out.push(b'&');
                        out.extend_from_slice(e.as_bytes());
                        out.push(b';');
                    }
                }
                None => {
                    let disallowed = flags & ENT_DISALLOWED != 0
                        && match uni {
                            Some(u) => !cp_is_allowed(u, doc),
                            None => false,
                        };
                    if disallowed {
                        out.extend_from_slice(replacement);
                    } else {
                        out.extend_from_slice(seq);
                    }
                }
            }
            continue;
        }
        // An ampersand.
        if double_encode {
            out.extend_from_slice(b"&amp;");
            continue;
        }
        // Keep an existing, valid entity verbatim.
        let kept: Option<usize> = if old.get(cursor) == Some(&b'#') {
            match parse_numeric_entity(old, cursor + 1) {
                Some((cp, semi)) => {
                    if flags & ENT_DISALLOWED != 0 && !numeric_entity_is_allowed(cp, doc) {
                        None
                    } else {
                        Some(semi)
                    }
                }
                None => None,
            }
        } else {
            match parse_named_entity(old, cursor) {
                Some((name, semi)) => resolve_named(name, doc, true).map(|_| semi),
                None => None,
            }
        };
        match kept {
            Some(semi) => {
                out.extend_from_slice(&old[before..=semi]);
                cursor = semi + 1;
            }
            None => out.extend_from_slice(b"&amp;"),
        }
    }
    out
}

/// php's `traverse_for_entities`: the decoder behind `html_entity_decode`
/// (`all` true) and `htmlspecialchars_decode` (`all` false).
fn unescape_html(old: &[u8], all: bool, flags: i64, cs: Charset) -> Vec<u8> {
    let doc = Doc::from_flags(flags);
    let mut out = Vec::with_capacity(old.len());
    let mut p = 0usize;
    while p < old.len() {
        if old[p] != b'&' {
            out.push(old[p]);
            p += 1;
            continue;
        }
        let decoded: Option<(u32, u32, usize)> = if old.get(p + 1) == Some(&b'#') {
            parse_numeric_entity(old, p + 2).and_then(|(cp, semi)| {
                let special = matches!(cp, 0x26 | 0x3c | 0x3e | 0x22 | 0x27);
                if !all && !special {
                    return None;
                }
                if !cp_is_allowed(cp, doc) || (doc == Doc::Html5 && cp == 0x0d) {
                    return None;
                }
                Some((cp, 0, semi))
            })
        } else {
            parse_named_entity(old, p + 1)
                .and_then(|(name, semi)| resolve_named(name, doc, all).map(|(a, b)| (a, b, semi)))
        };
        let Some((code, code2, semi)) = decoded else {
            out.push(b'&');
            p += 1;
            continue;
        };
        if (code == 0x27 && flags & ENT_HTML_QUOTE_SINGLE == 0)
            || (code == 0x22 && flags & ENT_HTML_QUOTE_DOUBLE == 0)
        {
            out.push(b'&');
            p += 1;
            continue;
        }
        // The target charset must be able to represent the result.
        let bytes = match cs.encode_cp(code) {
            Some(b) if code2 == 0 || cs == Charset::Utf8 => b,
            _ => {
                out.push(b'&');
                p += 1;
                continue;
            }
        };
        out.extend_from_slice(&bytes);
        if code2 != 0 {
            out.extend_from_slice(&utf8_encode(code2));
        }
        p = semi + 1;
    }
    out
}

/// The `(string, flags, encoding, double_encode)` argument shape shared by
/// `htmlspecialchars`/`htmlentities`.
fn encode_args(ctx: &mut Ctx, func: &str, args: &[Value]) -> Result<(Vec<u8>, i64, Charset, bool), Unwind> {
    let s = args[0].to_php_bytes();
    let flags = args.get(1).map_or(DEFAULT_FLAGS, Value::to_int);
    let hint = match args.get(2) {
        None | Some(Value::Null) => None,
        Some(v) => Some(v.to_php_bytes()),
    };
    let cs = Charset::from_hint(ctx, func, hint.as_deref())?;
    let double = args.get(3).is_none_or(Value::to_bool);
    Ok((s, flags, cs, double))
}

/// `htmlspecialchars(string $string, int $flags = ENT_QUOTES | ENT_SUBSTITUTE
/// | ENT_HTML401, ?string $encoding = null, bool $double_encode = true): string`.
pub(crate) fn htmlspecialchars(ctx: &mut Ctx, args: &mut [Value]) -> NativeResult {
    let (s, flags, cs, double) = encode_args(ctx, "htmlspecialchars", args)?;
    Ok(str_value(escape_html(&s, false, flags, cs, double)))
}

/// `htmlentities(...)`: every character with a named entity is converted.
pub(crate) fn htmlentities(ctx: &mut Ctx, args: &mut [Value]) -> NativeResult {
    let (s, flags, cs, double) = encode_args(ctx, "htmlentities", args)?;
    let mut all = true;
    if cs.is_multibyte() {
        ctx.notice("htmlentities(): Only basic entities substitution is supported for multi-byte encodings other than UTF-8; functionality is equivalent to htmlspecialchars")?;
        all = false;
    }
    Ok(str_value(escape_html(&s, all, flags, cs, double)))
}

/// `htmlspecialchars_decode(string $string, int $flags = ENT_QUOTES |
/// ENT_SUBSTITUTE | ENT_HTML401): string`.
pub(crate) fn htmlspecialchars_decode(_: &mut Ctx, args: &mut [Value]) -> NativeResult {
    let s = args[0].to_php_bytes();
    let flags = args.get(1).map_or(DEFAULT_FLAGS, Value::to_int);
    Ok(str_value(unescape_html(&s, false, flags, Charset::Utf8)))
}

/// `html_entity_decode(string $string, int $flags = ENT_QUOTES |
/// ENT_SUBSTITUTE | ENT_HTML401, ?string $encoding = null): string`.
pub(crate) fn html_entity_decode(ctx: &mut Ctx, args: &mut [Value]) -> NativeResult {
    let s = args[0].to_php_bytes();
    let flags = args.get(1).map_or(DEFAULT_FLAGS, Value::to_int);
    let hint = match args.get(2) {
        None | Some(Value::Null) => None,
        Some(v) => Some(v.to_php_bytes()),
    };
    let cs = Charset::from_hint(ctx, "html_entity_decode", hint.as_deref())?;
    Ok(str_value(unescape_html(&s, true, flags, cs)))
}

/// `get_html_translation_table(int $table = HTML_SPECIALCHARS, int $flags =
/// ENT_QUOTES | ENT_SUBSTITUTE | ENT_HTML401, string $encoding = "UTF-8"): array`.
pub(crate) fn get_html_translation_table(ctx: &mut Ctx, args: &mut [Value]) -> NativeResult {
    let table = args.first().map_or(0, Value::to_int);
    let flags = args.get(1).map_or(DEFAULT_FLAGS, Value::to_int);
    let hint = args.get(2).map(Value::to_php_bytes);
    let cs = Charset::from_hint(ctx, "get_html_translation_table", hint.as_deref())?;
    let doc = Doc::from_flags(flags);
    let mut all = table == 1;
    if all && cs.is_multibyte() {
        ctx.notice("get_html_translation_table(): Only basic entities substitution is supported for multi-byte encodings other than UTF-8; functionality is equivalent to htmlspecialchars")?;
        all = false;
    }
    let mut rows: Vec<(Vec<u8>, Vec<u8>)> = Vec::new();
    for cp in [0x22u32, 0x26, 0x27, 0x3c, 0x3e] {
        if let Some(e) = special_entity(cp, flags, doc) {
            // The XHTML entities table shares HTML 4.01's, which spells the
            // apostrophe `&#039;` (the specialchars table says `&apos;`).
            let e = if all && doc == Doc::Xhtml && cp == 0x27 { "&#039;" } else { e };
            rows.push((vec![cp as u8], e.as_bytes().to_vec()));
        }
    }
    if all {
        let single: &[(u32, &str)] = match doc {
            Doc::Html401 | Doc::Xhtml => HTML401_ENTITIES,
            Doc::Html5 => HTML5_ENTITIES,
            Doc::Xml1 => &[],
        };
        for &(cp, name) in single {
            // The MacRoman encode table has no tab/newline (see `to_unicode`).
            if cs == Charset::MacRoman && (cp == 0x09 || cp == 0x0a) {
                continue;
            }
            if let Some(key) = cs.encode_cp(cp) {
                rows.push((key, format!("&{name};").into_bytes()));
            }
        }
        if doc == Doc::Html5 {
            for &(a, b, name) in HTML5_ENTITIES_2 {
                // php checks only the first code point of a pair against
                // ISO-8859-1 and writes the second's low byte (kept for
                // exactness); the other charsets need both representable.
                let key = match cs {
                    Charset::Latin1 => match cs.encode_cp(a) {
                        Some(mut k) => {
                            k.push(b as u8);
                            k
                        }
                        None => continue,
                    },
                    _ => match (cs.encode_cp(a), cs.encode_cp(b)) {
                        (Some(mut k), Some(k2)) => {
                            k.extend_from_slice(&k2);
                            k
                        }
                        _ => continue,
                    },
                };
                rows.push((key, format!("&{name};").into_bytes()));
            }
        }
    }
    rows.sort_by(|a, b| a.0.cmp(&b.0));
    let mut out = Array::new();
    for (k, v) in rows {
        out.set(ArrayKey::str(&k), str_value(v));
    }
    Ok(Value::Array(out))
}

